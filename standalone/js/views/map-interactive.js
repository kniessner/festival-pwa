// ─── View ──────────────────────────────────────────────────────────────

export function renderInteractiveMap(container) {
    container.innerHTML = `
        <div class="festival-map" id="festivalMap"></div>
    `;

    const stage = container.querySelector('#festivalMap');

    // MapLibre pinch/drag flips gestureState.active during a gesture so
    // the shared sizeStage() can skip mid-gesture relayout (see
    // map-common.js for the reasoning — same iOS address-bar issue as
    // the static variant).
    const gestureState = { active: false };
    const detachSizing = attachStageSizing(stage, gestureState);

    // Defer map init until layout has settled — MapLibre reads container
    // width/height in its constructor and stashes them, so building it
    // before we've set the height would leave it thinking the canvas is
    // 0×0 until the next resize. `requestAnimationFrame` gives the browser
    // a paint to apply the style.height set by attachStageSizing above.
    //
    // The rAF handle + `cancelled` flag together kill the ownership race
    // where the user could switch tabs BEFORE createMap() runs: without
    // the guard the rAF would still fire, construct a fresh MapLibre
    // instance whose teardown has already run, and leak the WebGL
    // context + workers with nothing left to release them.
    let map;
    let cancelled = false;
    const rafId = requestAnimationFrame(() => {
        if (cancelled) return;
        map = createMap(stage, gestureState);
    });

    // Handed to the dispatcher (map.js), which owns invocation. Wrapped
    // in try/catch because MapLibre's own .remove() is not defensively
    // coded: if the user switches tabs before the async style load
    // finishes, `map` is defined but its workers/style aren't fully
    // wired, and .remove() hits an `undefined.destroy`. We'd rather leak
    // a not-yet-alive map than crash the tab switch.
    return () => {
        cancelled = true;
        cancelAnimationFrame(rafId);
        detachSizing();
        // User-location has its own listeners (watchPosition,
        // deviceorientation, visibilitychange, pointerdown-for-iOS).
        // Stop them BEFORE map.remove() so a straggling orientation
        // event can't try to write to a detached marker.
        if (map && typeof map.__userLocationStop === 'function') {
            try { map.__userLocationStop(); } catch (_) { /* nothing */ }
        }
        try {
            if (map) map.remove();
        } catch (err) {
            console.warn('[map] MapLibre .remove() threw during teardown — map was probably still initialising', err);
        }
    };
}

function createMap(stage, gestureState) {
    const maplibregl = window.maplibregl;
    if (!maplibregl) {
        stage.innerHTML =
            `<div class="festival-map-error">${t('common.noContent')}</div>`;
        return null;
    }

    // Register the pmtiles:// protocol so MapLibre can read our
    // precached Protomaps slice. addProtocol is a global registration —
    // if this view is remounted the second call overwrites with the same
    // handler, which is a no-op.
    if (window.pmtiles) {
        const protocol = new window.pmtiles.Protocol();
        maplibregl.addProtocol('pmtiles', protocol.tile);
    }

    const map = new maplibregl.Map({
        container: stage,
        style: buildStyle(),
        // Initial view — explicit center/zoom/bearing/pitch instead of a
        // fit-to-bounds so the tilt survives the first frame (fitBounds
        // recomputes the camera and clobbers any pitch we hand it).
        center: DEFAULT_CAMERA.center,
        zoom: DEFAULT_CAMERA.zoom,
        bearing: DEFAULT_CAMERA.bearing,
        pitch: DEFAULT_CAMERA.pitch,
        // Pan-limit — the user physically can't drag the camera outside
        // this bbox. MapLibre also implicitly bumps minZoom so the user
        // can't zoom out past the point where maxBounds would fit inside
        // the viewport, which is exactly what we want.
        maxBounds: MAP_MAX_BOUNDS,
        // Soft zoom floor. maxBounds already enforces its own implicit
        // floor (whatever zoom makes the bounds fit the viewport), so
        // this value is only relevant if we later loosen maxBounds.
        // Kept at 12 so there's headroom without a redeploy.
        minZoom: 12,
        maxZoom: 19,
        // Disable the built-in AttributionControl — it's hardcoded to
        // bottom-right. We add our own below at bottom-left instead.
        attributionControl: false,
    });

    // Attribution at bottom-left. Legal requirement (OSM + Protomaps)
    // so it stays visible; moved off bottom-right because MapLibre's
    // default position collides with the drop-up menu FAB in that
    // corner. `compact: false` forces the full attribution line to
    // render inline instead of collapsing behind an (i) button.
    map.addControl(new maplibregl.AttributionControl({ compact: false }), 'bottom-left');

    // Zoom-in/-out buttons and rotate-reset intentionally omitted — the
    // whole interaction is pinch / drag on touch. Attribution stays
    // (required by MapTiler + OSM).

    // Wire up gesture tracking so the resize handler above knows when to
    // skip. `touchstart` and `pointerdown` both trigger; either works.
    stage.addEventListener('pointerdown', () => { gestureState.active = true; });
    stage.addEventListener('pointerup', () => { gestureState.active = false; });
    stage.addEventListener('pointercancel', () => { gestureState.active = false; });

    map.on('load', () => addOverlayLayers(map));

    // User-location dot + heading cone. Started once the style is
    // ready so the marker can attach cleanly; the returned stop
    // function is stashed on the map for renderInteractiveMap's
    // teardown callback to invoke.
    map.on('load', () => {
        map.__userLocationStop = startUserLocation(map);
    });

    // Camera-state debug helper — commented out but preserved for
    // future rounds of default-tuning. Uncomment, deploy, and every
    // gesture-settle will log the current camera and copy a
    // paste-ready snippet to the clipboard.
    //
    // map.on('moveend', () => {
    //     const c = map.getCenter();
    //     const line = `center: [${c.lng.toFixed(6)}, ${c.lat.toFixed(6)}], zoom: ${map.getZoom().toFixed(2)}, bearing: ${map.getBearing().toFixed(1)}, pitch: ${map.getPitch().toFixed(1)}`;
    //     // eslint-disable-next-line no-console
    //     console.log('[map camera]', line);
    //     if (navigator.clipboard && navigator.clipboard.writeText) {
    //         navigator.clipboard.writeText(line).catch(() => { /* ignore */ });
    //     }
    // });

    // Track whether we've already surfaced a hard failure so we don't
    // paint the error overlay on top of a working map when a
    // late-arriving warning fires after load.
    let hardFailureShown = false;
    map.on('error', (e) => {
        const err = e && (e.error || e);
        // eslint-disable-next-line no-console
        console.error('[festival-map] MapLibre error', err);
        // A style-load failure (bad pmtiles URL, missing glyph range,
        // corrupted vendor bundle) is a hard failure — the user sees a
        // magenta rectangle and nothing else. Surface it via the same
        // .festival-map-error overlay used for the "no maplibregl" path.
        // Transient tile 404s (isSourceError with a fetchable source ID
        // that's not the basemap) shouldn't take the whole view down.
        const msg = String(err && (err.message || err)).toLowerCase();
        const styleBroken =
            msg.includes('style is not done loading') ||
            msg.includes('failed to fetch') ||
            msg.includes('pmtiles');
        if (styleBroken && !hardFailureShown && !map.isStyleLoaded()) {
            hardFailureShown = true;
            stage.innerHTML =
                `<div class="festival-map-error">${t('common.noContent')}</div>`;
        }
    });
    return map;
}

// Tier B illustrated basemap: Protomaps vector data (data/basemap.pmtiles)
// painted through a 58-layer paint stack derived from Protomaps'
// `light` theme, with every color slot remapped to the illustrated
// PNG palette (see map-palette.js) and every symbol/label layer
// suppressed (noLabelsWithCustomTheme). The layer array is baked once
// via `npm run build:basemap` → basemap-layers.js.
//
// Overlay geojsons (stages, venues, food, OSM zones, shore) stack on
// top via addOverlayLayers(). Basemap knows nothing about them.
//
// Layer names in the imported array come from Protomaps' schema:
// https://docs.protomaps.com/basemaps/layers
function buildStyle() {
    return {
        version: 8,
        // Local SDF glyphs (see standalone/glyphs/, generated by
        // scripts/generate-glyphs.js). Basemap has no labels of its
        // own — the glyphs are here for the overlay label layers we
        // paint on top (stages, venues, food).
        glyphs: 'glyphs/{fontstack}/{range}.pbf',
        sources: {
            basemap: {
                type: 'vector',
                url: 'pmtiles://data/basemap.pmtiles',
                attribution:
                    '\u00a9 <a href="https://openstreetmap.org" target="_blank">OpenStreetMap</a> \u00b7 <a href="https://protomaps.com" target="_blank">Protomaps</a>',
            },
        },
        // Pre-baked layer array with our PNG palette baked in. See
        // scripts/generate-basemap-layers.mjs for how it's produced and
        // js/views/map-palette.js for the source-of-truth palette.
        layers: basemapLayers,
    };
}

// ─── Overlay layers (Felt-derived geojsons on top of the basemap) ────
//
// Fresh start: five separate sources, one per Felt group. Each renders
// polygon fills, point circles (for markers/circles from Felt), and a
// label from the `text` property. No cross-group styling logic yet —
// Jacob wants to analyze the raw data first, then decide what to keep
// and how to differentiate visually. See standalone/data/felt/README.md
// for the schema.

// Distinct fill color per Felt group so overlapping features are still
// separable by eye. Deliberately loud/high-contrast for the analysis
// pass — will be re-tuned into the illustrated palette after review.
const FELT_LAYERS = [
    { id: 'gastro',          file: 'gastro.geojson',          color: '#ff9540' },
    { id: 'produktion',      file: 'produktion.geojson',      color: '#8b7fa8' },
    { id: 'stages',          file: 'stages.geojson',          color: '#c22a4c' },
    { id: 'sterne',          file: 'sterne.geojson',          color: '#ffd166' },
    { id: 'toilets-showers', file: 'toilets-showers.geojson', color: '#4ecdc4' },
];

function addOverlayLayers(map) {
    for (const { id, file, color } of FELT_LAYERS) {
        map.addSource(id, {
            type: 'geojson',
            data: 'data/' + file,
        });

        // Polygon / MultiPolygon fill + outline.
        map.addLayer({
            id: id + '-fill',
            source: id,
            type: 'fill',
            filter: ['==', ['geometry-type'], 'Polygon'],
            paint: { 'fill-color': color, 'fill-opacity': 0.5 },
        });
        map.addLayer({
            id: id + '-outline',
            source: id,
            type: 'line',
            filter: ['==', ['geometry-type'], 'Polygon'],
            paint: { 'line-color': color, 'line-width': 1.2, 'line-opacity': 0.9 },
        });

        // Point features (Felt Markers / Circles come through as Points).
        map.addLayer({
            id: id + '-point',
            source: id,
            type: 'circle',
            filter: ['==', ['geometry-type'], 'Point'],
            paint: {
                'circle-color': color,
                'circle-radius': 4,
                'circle-stroke-color': PNG_MAGENTA_HALO,
                'circle-stroke-width': 1,
            },
        });

        // Labels — the Felt `text` property is the human-readable name
        // for the feature. Rendered at every zoom for now; Jacob will
        // finetune zoom stops once we've decided which layers stay.
        map.addLayer({
            id: id + '-label',
            source: id,
            type: 'symbol',
            filter: ['has', 'text'],
            layout: {
                'text-field': ['get', 'text'],
                'text-font': FONT_HELPER,
                'text-size': 11,
                'text-anchor': 'center',
                'text-max-width': 8,
                'text-allow-overlap': false,
                'text-optional': true,
                'text-padding': 2,
                'text-rotation-alignment': 'viewport',
                'text-pitch-alignment': 'viewport',
            },
            paint: {
                'text-color': PNG_CREAM,
                'text-halo-color': PNG_MAGENTA_HALO,
                'text-halo-width': 1.4,
            },
        });
    }

    // Click popup — reads whichever Felt layer's fill / point was hit.
    // Layers list is derived from FELT_LAYERS so it stays in sync if we
    // add or remove groups.
    const interactiveLayerIds = FELT_LAYERS.flatMap(({ id }) => [
        id + '-fill', id + '-point',
    ]);
    map.on('click', (e) => {
        const features = map.queryRenderedFeatures(e.point, {
            layers: interactiveLayerIds,
        });
        if (!features.length) return;
        const f = features[0];
        const p = f.properties || {};
        const name = p.text || '';
        const desc = p.description || '';
        const cat = p.symbol || '';
        new window.maplibregl.Popup({ closeButton: true, offset: 8 })
            .setLngLat(e.lngLat)
            .setHTML(`
                <div class="festival-map-popup">
                    <div class="festival-map-popup-title">${escapeHtml(name)}</div>
                    ${cat ? `<div class="festival-map-popup-cat">${escapeHtml(String(cat))}</div>` : ''}
                    ${desc ? `<div class="festival-map-popup-desc">${escapeHtml(desc)}</div>` : ''}
                </div>
            `)
            .addTo(map);
    });

    interactiveLayerIds.forEach((id) => {
        map.on('mouseenter', id, () => { map.getCanvas().style.cursor = 'pointer'; });
        map.on('mouseleave', id, () => { map.getCanvas().style.cursor = ''; });
    });
}
