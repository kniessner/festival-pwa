// NOTE for future contributors: an earlier revision loaded label glyphs
// from api.maptiler.com/fonts/{fontstack}/{range}.pbf with a signed
// URL. The vendored SDF glyphs under standalone/glyphs/ (generated by
// scripts/generate-glyphs.js) replaced that, so we no longer need any
// third-party glyph service or API key. If MapTiler ever comes back as
